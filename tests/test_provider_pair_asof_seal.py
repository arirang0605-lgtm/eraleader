@pytest.mark.parametrize("mutation",[
    "append_bytes","delete","symlink","public_mode","replace_original",
])
def test_first_pair_receipt_corruption_cannot_be_a_new_source_claim(published,mutation,tmp_path):
    pair,initial,root=published
    target=root/"first_pair_receipt.json"
    raw=target.read_bytes()
    if mutation=="append_bytes":
        target.write_bytes(raw+b"bad")
    elif mutation=="delete":
        target.unlink()
    elif mutation=="symlink":
        target.unlink()
        dummy=tmp_path/"replacement_receipt.json"
        dummy.write_bytes(raw)
        target.symlink_to(dummy)
    elif mutation=="public_mode":
        target.chmod(0o644)
    else:
        doc=json.loads(raw)
        doc["first_ingest_at_utc"]=(NOW-timedelta(days=2)).isoformat()
        target.write_bytes((json.dumps(doc,sort_keys=True,separators=(",",":"))+"\n").encode())
    with pytest.raises((ValueError,OSError)):
        examine(published,at=NOW+timedelta(hours=1))


