def test_previous_agreement_does_not_override_later_empty_active_universe(tmp_path):
    pair=make_pair(tmp_path)
    for source in pair[:2]:
        revise_stream(source,"membership",
            lambda rows:rows[0].update(delisted_on="2026-10-12"))
    imported=run(pair)
    root=pair[2]/"first_pair"
    first=audit.audit_atomic_provider_pair_asof(
        root,imported["first_pair_receipt_sha256"],
        decision_at=NOW.isoformat(),clock=NOW)
    assert first["status"]==audit.READY
    later=NOW+timedelta(days=3)
    after=audit.audit_atomic_provider_pair_asof(
        root,imported["first_pair_receipt_sha256"],
        decision_at=later.isoformat(),clock=later)
    assert after["status"]==audit.CONFLICT
    assert after["eligible_for_local_candidate_watch_research_only"] is False
    assert after["matched_active_declared_securities_at_asof"]==0
    assert after["blocker_counts"]
    assert after["official_pit_certified"] is False


def test_cli_valid_private_pair_asof_then_fail_closed_on_reissue(published):
    pair,first,root=published
    args=[sys.executable,str(CLI),"--project",str(ROOT),
          "--pair-root",str(root),
          "--first-pair-sha256",first["first_pair_receipt_sha256"],
          "--as-of",(NOW+timedelta(minutes=1)).isoformat()]
    result=subprocess.run(args,cwd=ROOT,capture_output=True,text=True)
    assert result.returncode==0,result.stderr
    body=json.loads(result.stdout)
    assert body["status"]==audit.READY
    assert body["official_leader_promotions"]==0
    assert body["external_api_calls"]==0
    assert str(pair[0]) not in result.stdout
    assert str(pair[1]) not in result.stdout
    failed=subprocess.run(args[:-4]+[
        "--pair-root",str(root),
        "--first-pair-sha256","f"*64,
        "--as-of",NOW.isoformat()],cwd=ROOT,capture_output=True,text=True)
    assert failed.returncode==2
    assert str(pair[0]) not in failed.stderr and str(pair[1]) not in failed.stderr
