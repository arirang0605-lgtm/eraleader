def test_registered_sqlite_source_records_not_autorepaired_or_reenrolled(published):
    pair,original,root=published
    ledger=root/"source_b"/"offline.sqlite"
    before=sha256(ledger.read_bytes()).hexdigest()
    conn=sqlite3.connect(ledger)
    try:
        conn.execute("UPDATE offline_records SET payload=? WHERE rowid=(SELECT MIN(rowid) FROM offline_records)",('{"fake":true}',))
        conn.commit()
    finally:
        conn.close()
    with pytest.raises((ValueError,sqlite3.DatabaseError,RuntimeError)):
        examine(published,at=NOW+timedelta(hours=1))
    assert sha256(ledger.read_bytes()).hexdigest()!=before
    # A read-only audit must never restore the rewritten record or register a
    # fresh first receipt from the broken file.


