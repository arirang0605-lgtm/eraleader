@pytest.mark.parametrize("market",["KR","US"])
def test_original_pair_receipt_exposes_stable_asof_still_research_only(tmp_path,market):
    pair=make_pair(tmp_path,market)
    original=run(pair)
    root=pair[2]/"first_pair"
    first=root/"first_pair_receipt.json"
    checksum=sha256(first.read_bytes()).hexdigest()
    assert checksum==original["first_pair_receipt_sha256"]
    now=NOW+timedelta(hours=1)
    report=audit.audit_atomic_provider_pair_asof(
        root,checksum,decision_at=now.isoformat(),clock=now)
    assert report["status"]==audit.READY
    assert report["market"]==market
    assert report["matched_active_declared_securities_at_asof"]==1
    assert report["source_a_bundle_sha256"]==original[
        "source_a_normalized_manifest_sha256"]
    assert report["source_b_bundle_sha256"]==original[
        "source_b_normalized_manifest_sha256"]
    assert report["eligible_for_local_candidate_watch_research_only"] is True
    assert report["official_pit_certified"] is False
    assert report["permanent_issuer_and_class_attested"] is False
    assert report["independent_publisher_and_timestamp_attested"] is False
    assert report["real_future_leader_precision"] is None
    assert report["messages_sent"]==report["external_api_calls"]==0
    assert first.read_bytes().endswith(b"\n")
    assert len(first.read_bytes())<audit.MAX_RECEIPT
    assert not list(root.parent.glob(".eraleader_pair_ingest_*"))


